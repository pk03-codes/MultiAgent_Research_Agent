@app.post("/api/research", response_model=ResearchResponse)
def execute_research(payload: ResearchRequest):
    """
    Executes the multi-agent research pipeline:
    1. Search Agent: Queries arXiv and Tavily web index.
    2. Reader Agent: Scrapes deep full-text articles.
    3. Writer Agent: Generates structured scientific report.
    4. Critic Agent: Evaluates facts and citations with self-correction loop.
    """
    topic = payload.topic.strip()
    if not topic:
        raise HTTPException(status_code=400, detail="Research topic cannot be empty.")

    try:
        print(f"\n[API] Initiating Coeus Research Pipeline for: '{topic}'")
        state = run_research_pipeline(topic)

        report_markdown = stringify(state.get("report", "No report was generated."))
        feedback = stringify(state.get("feedback", ""))
        raw_search = state.get("search_results", "")
        sources = extract_sources_from_raw(raw_search, topic)

        new_entry = {
            "id": f"rec-{int(datetime.now().timestamp())}",
            "title": topic,
            "date": "Today",
            "report": report_markdown,
            "sources": [s.model_dump() for s in sources],
            "feedback": feedback,
        }

        # Persist to local backend history
        existing = load_history()
        existing = [item for item in existing if item.get("title") != topic]
        existing.insert(0, new_entry)
        save_history(existing[:30])

        return ResearchResponse(
            id=new_entry["id"],
            title=new_entry["title"],
            date=new_entry["date"],
            report=new_entry["report"],
            sources=sources,
            feedback=feedback,
        )

    except Exception as e:
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=f"Research execution failed: {str(e)}")


@app.get("/api/history", response_model=List[ResearchResponse])
def get_history():
    """Fetches previously saved research dossiers from server storage."""
    records = load_history()
    formatted = []
    for r in records:
        try:
            formatted.append(ResearchResponse(
                id=r["id"],
                title=r["title"],
                date=r.get("date", "Recent"),
                report=r["report"],
                sources=[SourceItem(**s) for s in r.get("sources", [])],
                feedback=r.get("feedback", ""),
            ))
        except Exception:
            continue
    return formatted


