import os
from dotenv import load_dotenv
from langchain.agents import create_agent
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser

try:
    from tools import web_search, scrape_url, search_arxiv
except ModuleNotFoundError:
    from backend.tools import web_search, scrape_url, search_arxiv

load_dotenv()
load_dotenv(os.path.join(os.path.dirname(__file__), ".env"))

google_api_key = os.getenv("GOOGLE_API_KEY") or os.getenv("GEMINI_API_KEY")
if not google_api_key:
    raise RuntimeError(
        "Set GOOGLE_API_KEY or GEMINI_API_KEY in the environment or .env file."
    )

# Use official Gemini model (fast, high rate limits, and multimodal)
llm = ChatGoogleGenerativeAI(
    model="gemini-3.5-flash-lite",
    api_key=google_api_key,
    timeout=120,
    max_retries=5,
)

# 1st Agent: Literature & Web Search (Tavily + arXiv)
def build_search_agent():
    return create_agent(
        model=llm,
        tools=[web_search, search_arxiv]
    )

# 2nd Agent: Deep Reader & Scraper
def build_reader_agent():
    return create_agent(
        model=llm,
        tools=[scrape_url]
    )

# 3rd Agent: Writer Chain
writer_prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        """
        You are an expert Research Writer, Analytical Thinker, and
        Professional Content Synthesizer.

        Your responsibility is to transform the research materials
        provided by the research agents into a comprehensive,
        accurate, well-structured, and professionally written report.

        Follow these guidelines:

        1. CONTENT SYNTHESIS:
           - Carefully analyze all the provided research findings.
           - Combine relevant information from different sources.
           - Eliminate redundant, irrelevant, or repetitive content.
           - Identify important insights, patterns, and relationships.
           - Maintain logical flow and consistency throughout the report.

        2. ACCURACY AND RELIABILITY:
           - Use only the information available in the research materials.
           - Never fabricate facts, statistics, references, or conclusions.
           - Clearly distinguish verified facts from interpretations.
           - Highlight conflicting information when different sources disagree.
           - Preserve source URLs for factual traceability.

        3. REPORT STRUCTURE:
           Organize the report using the following structure:
           - Title
           - Executive Summary
           - Introduction and Background
           - Detailed Research Findings
           - Key Insights and Analysis
           - Supporting Evidence and Sources
           - Conclusion

        4. WRITING STYLE:
           - Maintain a formal, professional, and objective tone.
           - Use clear and precise language.
           - Avoid unnecessary jargon and exaggerated claims.
           - Use appropriate headings, subheadings, and bullet points.
           - Ensure the report is comprehensive but not unnecessarily verbose.

        5. SOURCE ATTRIBUTION:
           - Include relevant source URLs alongside supporting claims.
           - Do not create fictional citations.
           - Ensure that conclusions are supported by the available evidence.

        Your final output must be a polished, publication-ready research
        report that demonstrates clarity, analytical depth, factual
        consistency, and professional presentation.

        Return only the final research report.
        """
    ),
    (
        "human",
        """
        Research Topic:
        {topic}

        Research Materials:
        {research_material}

        Based on the research materials provided above, prepare a
        comprehensive and professionally structured research report.

        Ensure that all important findings are synthesized, relevant
        evidence is retained, and the final report is logically organized.
        """
    )
])

writer_chain = writer_prompt | llm | StrOutputParser()

# 4th Agent: Critic QA Chain
critic_prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        """
        You are an expert Research Critic, Fact-Checking Analyst,
        and Quality Assurance Specialist.

        Your responsibility is to critically evaluate research reports
        generated by the Writer Agent and ensure that the final output
        meets high standards of accuracy, reliability, analytical depth,
        and professional quality.

        Evaluate the report using the following criteria:

        1. FACTUAL ACCURACY:
           - Identify potentially inaccurate or misleading statements.
           - Detect unsupported claims, fabricated statistics, or assumptions.
           - Check whether factual statements are supported by research materials.
           - Identify inconsistencies between the report and its sources.

        2. COMPLETENESS:
           - Determine whether all important research findings are covered.
           - Identify missing information or overlooked perspectives.
           - Check whether the report adequately addresses the research topic.

        3. LOGICAL CONSISTENCY:
           - Examine the logical flow of arguments and conclusions.
           - Identify contradictions, weak reasoning, and unsupported deductions.

        4. SOURCE QUALITY:
           - Evaluate the relevance and credibility of cited sources.
           - Identify missing citations and unverifiable references.

        5. WRITING QUALITY:
           - Evaluate clarity, readability, and professional tone.
           - Identify unnecessary repetition and irrelevant content.

        FINAL VERDICT:
        Assign one of the following verdicts at the very end:
        - FINAL VERDICT: APPROVED (The report meets high standards)
        - FINAL VERDICT: NEEDS REVISION (The report has factual or completeness gaps)
        - FINAL VERDICT: REJECTED (Serious factual inaccuracies)

        OUTPUT FORMAT:
        1. Overall Assessment
        2. Factual Accuracy Evaluation
        3. Completeness Evaluation
        4. Logical Consistency Evaluation
        5. Source Reliability Evaluation
        6. Writing Quality Evaluation
        7. Identified Issues
        8. Recommended Improvements
        9. FINAL VERDICT: [APPROVED / NEEDS REVISION / REJECTED]
        """
    ),
    (
        "human",
        """
        Research Report:
        {report}

        Actual Research Material:
        {research_material}

        Critically evaluate the generated research report against
        the original research materials. Provide a structured evaluation
        and conclude with: FINAL VERDICT: [APPROVED / NEEDS REVISION / REJECTED]
        """
    )
])

critic_chain = critic_prompt | llm | StrOutputParser()

# 5th Component: Self-Correction Revision Chain
revision_prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        """
        You are an expert Research Editor. Your goal is to improve and revise
        the research report based on the specific critique provided by the Critic Agent.

        Guidelines:
        1. Address all identified issues and recommendations raised in the critique.
        2. Strengthen factual grounding using the original research materials.
        3. Maintain the structured format (Executive Summary, Background, Findings, Analysis, Sources, Conclusion).
        4. Keep all valid citations and preserve accuracy.
        """
    ),
    (
        "human",
        """
        Research Topic:
        {topic}

        Previous Report Draft:
        {original_report}

        Critic Feedback:
        {critic_feedback}

        Original Research Materials:
        {research_material}

        Please provide the fully revised and improved research report:
        """
    )
])

revision_chain = revision_prompt | llm | StrOutputParser()
